export function enemyById(id: EnemyId): EnemyDef {
  return BY_ID[id] ?? DEFAULT_ENEMY;
}

/** 系統だけの簡易選択（フォールバック用） */
export function enemyForSystem(system?: SystemKind | null): EnemyDef {
  if (!system) return DEFAULT_ENEMY;
  return BY_SYSTEM[system] ?? DEFAULT_ENEMY;
}

/**
 * ゲート内容から敵を選ぶ。
 * auth / fog を系統より優先し、それ以外は SystemKind に対応。
 */
export function enemyForGate(input: {
  system?: SystemKind | null;
  text?: string | null;
  domain?: string | null;
}): EnemyDef {
  const blob = [input.text, input.domain]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  if (
    /auth|ログイン|にんしょう|認証|oidc|oauth|token|クレーム|jwt|sso|本人確認/.test(
      blob,
    )
  ) {
    return ENEMY_AUTH;
  }
  if (/霧|もや|未特定|unknown|fog/.test(blob)) {
    return ENEMY_FOG;
  }
  if (!input.system || input.system === "other") {
    // 手がかりが弱いときは霧寄り（完全な other はスライム）
    if (!blob.trim()) return ENEMY_FOG;
  }
  return enemyForSystem(input.system);
}

export function paintEnemyFrame(
  ctx: CanvasRenderingContext2D,
  def: EnemyDef = DEFAULT_ENEMY,
  frameIndex: number,
  scale = 2,
) {
  const rows = def.frames[frameIndex % def.frames.length].split("\n");
  ctx.clearRect(0, 0, 32 * scale, 32 * scale);
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y] ?? "";
    for (let x = 0; x < row.length; x++) {
      const col = def.palette[row[x]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
}
