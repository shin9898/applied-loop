/**
 * Pixel enemy sprites for understanding-gate battles.
 * ~10 kinds: SystemKind 8 + fog + auth. Distinct silhouettes, 2 frames each.
 */
import type { SystemKind } from "@/lib/atlas-taxonomy";

export type EnemyId =
  | SystemKind
  | "fog"
  | "auth";

export type EnemyDef = {
  id: EnemyId;
  name: string;
  frames: string[];
  palette: Record<string, string | null>;
};

function pack(rows: string[]): string {
  return rows.join("\n");
}

/** Shared palette keys: 8 outline, 0 dark, f body, w eye/white, g accent, a alt, b alt2 */
type Pal = Record<string, string | null>;

function enemy(
  id: EnemyId,
  name: string,
  palette: Pal,
  frameA: string[],
  frameB: string[],
): EnemyDef {
  return { id, name, palette, frames: [pack(frameA), pack(frameB)] };
}

